//! Text outputs built from the manifest, `themes.json` and the blueprints.
//! Pure functions, so `gallery check` can rebuild them and compare.

use crate::build::PREVIEW;
use crate::manifest::{self, RAW_BASE, REPO, Row, SITE};
use crate::model::{Blueprint, Theme, blueprint_path, preview_path, read_blueprint};
use anyhow::{Context, Result, bail};
use std::collections::BTreeMap;
use std::fmt::Write;
use std::path::{Path, PathBuf};

pub const INSTALL: &str = "curl -fsSL https://raw.githubusercontent.com/justcarlson/omarchy-wallpapers/main/install.sh | bash";

pub struct Inputs {
    pub rows: Vec<Row>,
    pub themes: BTreeMap<String, Theme>,
    pub blueprints: BTreeMap<(String, String), Blueprint>,
}

pub fn load(root: &Path) -> Result<Inputs> {
    let rows = manifest::read(&root.join("wallpapers.tsv"))?;
    manifest::validate(&rows)?;
    let themes: BTreeMap<String, Theme> =
        serde_json::from_str(&std::fs::read_to_string(root.join("themes.json")).context("read themes.json; run `gallery build`")?)?;
    let mut blueprints = BTreeMap::new();
    for r in &rows {
        if !themes.contains_key(&r.theme) {
            bail!("themes.json has no {}; run `gallery build`", r.theme);
        }
        blueprints.insert((r.theme.clone(), r.slug().to_string()), read_blueprint(root, r)?);
    }
    Ok(Inputs { rows, themes, blueprints })
}

/// Every generated text file, by path relative to the repository root.
pub fn outputs(root: &Path, inputs: &Inputs) -> Result<BTreeMap<PathBuf, String>> {
    let mut files = BTreeMap::new();
    let readme = std::fs::read_to_string(root.join("README.md")).context("read README.md")?;
    files.insert("README.md".into(), readme_with_gallery(&readme, inputs)?);
    for (theme, rows) in manifest::by_theme(&inputs.rows) {
        files.insert(PathBuf::from(format!("themes/{theme}.md")), theme_page(&inputs.themes[theme], theme, &rows));
    }
    files.insert("docs/index.html".into(), site(inputs));
    Ok(files)
}

fn escape(text: &str) -> String {
    text.replace('&', "&amp;").replace('<', "&lt;").replace('>', "&gt;").replace('"', "&quot;")
}

fn percent_encode(text: &str) -> String {
    text.bytes()
        .map(|b| match b {
            b'A'..=b'Z' | b'a'..=b'z' | b'0'..=b'9' | b'-' | b'_' | b'.' | b'~' => (b as char).to_string(),
            _ => format!("%{b:02X}"),
        })
        .collect()
}

fn blueprint_url(row: &Row) -> String {
    format!("{RAW_BASE}/{}", blueprint_path(row).display())
}

fn aether_link(row: &Row) -> String {
    format!("aether://apply?external_theme={}", percent_encode(&blueprint_url(row)))
}

fn plural(n: usize, word: &str) -> String {
    format!("{n} {word}{}", if n == 1 { "" } else { "s" })
}

fn replace_block(text: &str, name: &str, body: &str) -> Result<String> {
    let start = format!("<!-- {name}:start -->");
    let end = format!("<!-- {name}:end -->");
    let (Some(a), Some(b)) = (text.find(&start), text.find(&end)) else {
        bail!("README.md is missing the {start} … {end} markers");
    };
    Ok(format!("{}{start}\n{body}{}", &text[..a], &text[b..]))
}

fn readme_with_gallery(readme: &str, inputs: &Inputs) -> Result<String> {
    let groups = manifest::by_theme(&inputs.rows);
    let stats = format!(
        "**{} wallpapers for {} Omarchy themes**, each with an Aether palette.\n",
        inputs.rows.len(),
        groups.len()
    );
    let mut gallery = String::from("<table>\n");
    let entries: Vec<_> = groups.iter().collect();
    for pair in entries.chunks(2) {
        gallery.push_str("<tr>\n");
        for (theme, rows) in pair {
            let title = &inputs.themes[**theme].title;
            writeln!(
                gallery,
                "<td width=\"50%\" valign=\"top\"><a href=\"themes/{theme}.md\"><img src=\"docs/mosaics/{theme}.jpg\" alt=\"{} {title} wallpapers\"></a><br><a href=\"themes/{theme}.md\"><b>{title}</b></a> · {}</td>",
                rows.len(),
                plural(rows.len(), "wallpaper")
            )
            .unwrap();
        }
        gallery.push_str("</tr>\n");
    }
    gallery.push_str("</table>\n");
    let text = replace_block(readme, "stats", &stats)?;
    replace_block(&text, "gallery", &gallery)
}

fn theme_page(theme: &Theme, name: &str, rows: &[&Row]) -> String {
    let title = &theme.title;
    let mut page = format!(
        "<!-- Generated by `gallery render` from wallpapers.tsv. Do not edit. -->\n\n\
         # {title}\n\n\
         <a href=\"{SITE}/#{name}\"><img src=\"../docs/mosaics/{name}.jpg\" alt=\"All {count} {title} wallpapers\"></a>\n\n\
         {count_text} picked for {title} by how closely Aether's palette for each image matches the theme's colours.\n\n\
         Install just this set:\n\n\
         ```sh\n{INSTALL} -s -- {name}\n```\n\n\
         Then press <kbd>Super</kbd> <kbd>Ctrl</kbd> <kbd>Space</kbd> to pick one. \
         To build a whole new theme from a wallpaper instead, import its Aether blueprint:\n\n\
         ```sh\naether --import-blueprint {RAW_BASE}/blueprints/{name}/<name>.json --auto-apply\n```\n\n\
         <table>\n",
        count = rows.len(),
        count_text = plural(rows.len(), "wallpaper"),
    );
    for pair in rows.chunks(2) {
        page.push_str("<tr>\n");
        for row in pair {
            let credit = row.credit();
            writeln!(
                page,
                "<td width=\"50%\" valign=\"top\"><a href=\"{url}\"><img src=\"../{preview}\" alt=\"{alt}\"></a><br><b>{alt}</b><br><sub><a href=\"{credit_url}\">{credit}</a> · <a href=\"../{blueprint}\">Aether blueprint</a></sub></td>",
                url = escape(&row.url()),
                preview = preview_path(row).display(),
                alt = escape(&row.title()),
                credit_url = escape(&credit.url),
                credit = escape(&credit.label),
                blueprint = blueprint_path(row).display(),
            )
            .unwrap();
        }
        page.push_str("</tr>\n");
    }
    page.push_str("</table>\n\n[All themes](../README.md#the-collection)\n");
    page
}

const STYLE: &str = include_str!("site.css");
const SCRIPT: &str = include_str!("site.js");

fn site(inputs: &Inputs) -> String {
    let groups = manifest::by_theme(&inputs.rows);
    let mut html = String::new();
    write!(
        html,
        r##"<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Omarchy Wallpapers</title>
<meta name="description" content="{count} wallpapers for {themes} Omarchy themes, each matched to its theme by Aether and shipped with an Aether palette.">
<meta property="og:title" content="Omarchy Wallpapers">
<meta property="og:description" content="{count} wallpapers for {themes} Omarchy themes. One command installs them.">
<meta property="og:image" content="{SITE}/hero.jpg">
<meta name="twitter:card" content="summary_large_image">
<link rel="icon" href="data:image/svg+xml,%3Csvg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 16 16'%3E%3Crect width='16' height='16' rx='3' fill='%23d8a657'/%3E%3Crect x='3' y='9' width='10' height='4' fill='%23282828'/%3E%3C/svg%3E">
<style>{STYLE}</style>
</head>
<body>
<header class="top">
  <img class="hero" src="hero.jpg" alt="One wallpaper from each theme in the collection" width="2400" height="900">
  <div class="intro">
    <h1>Omarchy Wallpapers</h1>
    <p class="lede">{count} wallpapers for {themes} Omarchy themes. Aether scored every image against its theme's colours, and every one ships with the Aether palette it makes.</p>
    <div class="command"><code id="install">{INSTALL}</code><button type="button" data-copy="install">Copy</button></div>
    <p class="hint">Installs the sets for the themes you have. Then press <kbd>Super</kbd> <kbd>Ctrl</kbd> <kbd>Space</kbd>. <a href="https://github.com/{REPO}">Source and options on GitHub</a>.</p>
  </div>
  <nav class="themes" aria-label="Themes">
"##,
        count = inputs.rows.len(),
        themes = groups.len(),
    )
    .unwrap();
    for theme in groups.keys() {
        let t = &inputs.themes[*theme];
        writeln!(
            html,
            r##"    <a href="#{theme}" style="--bg:{};--fg:{};--accent:{}">{}</a>"##,
            t.background,
            t.foreground,
            t.accent,
            escape(&t.title)
        )
        .unwrap();
    }
    html.push_str("  </nav>\n</header>\n<main>\n");
    for (theme, rows) in &groups {
        let t = &inputs.themes[*theme];
        writeln!(
            html,
            r#"<section id="{theme}" class="theme {mode}" style="--bg:{bg};--fg:{fg};--accent:{accent}">
  <div class="theme-head">
    <h2>{title}</h2>
    <span class="count">{count}</span>
    <div class="command small"><code id="install-{theme}">{INSTALL} -s -- {theme}</code><button type="button" data-copy="install-{theme}">Copy</button></div>
  </div>
  <div class="grid">"#,
            mode = t.mode,
            bg = t.background,
            fg = t.foreground,
            accent = t.accent,
            title = escape(&t.title),
            count = plural(rows.len(), "wallpaper"),
        )
        .unwrap();
        for row in rows {
            let blueprint = &inputs.blueprints[&(row.theme.clone(), row.slug().to_string())];
            let credit = row.credit();
            let swatches: String = blueprint
                .palette
                .colors
                .iter()
                .map(|c| format!(r#"<i style="background:{c}" title="{c}"></i>"#))
                .collect();
            writeln!(
                html,
                r#"    <figure>
      <a class="shot" href="{url}"><img src="{preview}" alt="{title}" width="{w}" height="{h}" loading="lazy" decoding="async"></a>
      <div class="palette" aria-label="Aether palette">{swatches}</div>
      <figcaption><strong>{title}</strong><a class="credit" href="{credit_url}">{credit}</a></figcaption>
      <div class="actions"><a href="{aether}" title="Opens Aether with this palette and wallpaper">Open in Aether</a><a href="{blueprint_url}">Blueprint</a><a href="{url}">Full size</a></div>
    </figure>"#,
                url = escape(&row.url()),
                preview = preview_path(row).strip_prefix("docs").unwrap().display(),
                title = escape(&row.title()),
                w = PREVIEW.0,
                h = PREVIEW.1,
                credit_url = escape(&credit.url),
                credit = escape(&credit.label),
                aether = escape(&aether_link(row)),
                blueprint_url = escape(&blueprint_url(row)),
            )
            .unwrap();
        }
        html.push_str("  </div>\n</section>\n");
    }
    write!(
        html,
        r#"</main>
<footer>
  <p>Images belong to their creators; each card links to its source. Paintings are public domain. <a href="https://github.com/{REPO}#credits">Credits and licences</a>.</p>
  <p>Made for <a href="https://omarchy.org">Omarchy</a>. Palettes by <a href="https://github.com/omacom/aether">Aether</a>.</p>
</footer>
<script>{SCRIPT}</script>
</body>
</html>
"#
    )
    .unwrap();
    html
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn aether_links_encode_the_blueprint_url() {
        let row = Row { theme: "gruvbox".into(), sha256: "a".repeat(64), file: "curated-x y.jpg".into(), source: "images/x.jpg".into(), origin: None };
        assert_eq!(
            aether_link(&row),
            "aether://apply?external_theme=https%3A%2F%2Fraw.githubusercontent.com%2Fjustcarlson%2Fomarchy-wallpapers%2Fmain%2Fblueprints%2Fgruvbox%2Fx%20y.json"
        );
    }

    #[test]
    fn readme_blocks_are_replaced_in_place() {
        let text = "a\n<!-- x:start -->\nold\n<!-- x:end -->\nb\n";
        assert_eq!(replace_block(text, "x", "new\n").unwrap(), "a\n<!-- x:start -->\nnew\n<!-- x:end -->\nb\n");
        assert!(replace_block("none", "x", "").is_err());
    }
}
